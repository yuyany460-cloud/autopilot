"""Agent 提示词。

提示词决定了一个"电脑操控智能体"是否可靠。这里的关键约定：

1. **每轮只做一个动作**——并行调用会让状态推理失控。
2. **优先用元素编号而不是坐标**——E7 来自刚采集的 UIA 快照，
   而模型"目测"像素坐标几乎必错。
3. **执行后系统会自动给新快照**——避免模型浪费一轮去 observe。
4. **失败要换策略而不是重试同一个动作**——这是最常见的死循环来源。
"""

